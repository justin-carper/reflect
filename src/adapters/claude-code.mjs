// Claude Code adapter.
//
// Storage layout, under ~/.claude/projects/<slugified-cwd>/<sessionId>.jsonl:
// one JSON object per line, discriminated by `type`. Relevant types are
// `user` and `assistant`; the file also carries `system`, `attachment`,
// `file-history-snapshot`, `last-prompt`, `permission-mode`, `queue-operation`,
// `ai-title`, `mode`, `pr-link`, `custom-title`, `agent-name`.
//
// The filter is a negative test, matching the opencode adapter's shape. There
// is no reliable positive marker for human input: `promptSource: "typed"` was
// present on only 2 of 315 user records in a real corpus, so requiring it would
// discard almost everything.
//
// Records excluded, and why:
//   isSidechain      subagent session; the "user" text is a prompt the agent wrote
//   isMeta           harness-injected notice, not typed by anyone
//   toolUseResult    tool output delivered as a user record (59% of user records)
//   sourceToolUseID  message generated by a tool rather than a person
//
// Validation: on a real corpus this filter returned 104 human messages where an
// independent hand-written mine of the same files found ~99.

import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'

export const name = 'claude-code'
export const label = 'Claude Code'

const ROOT = () =>
  process.env.REFLECT_CLAUDE_PROJECTS || path.join(os.homedir(), '.claude/projects')

export function detect() {
  const r = ROOT()
  if (!fs.existsSync(r)) return false
  try {
    return fs
      .readdirSync(r, { withFileTypes: true })
      .some((e) => e.isDirectory() && fs.readdirSync(path.join(r, e.name)).some((f) => f.endsWith('.jsonl')))
  } catch {
    return false
  }
}

const transcripts = () => {
  const r = ROOT()
  const out = []
  let dirs
  try {
    dirs = fs.readdirSync(r, { withFileTypes: true })
  } catch {
    return out
  }
  for (const d of dirs) {
    if (!d.isDirectory()) continue
    let files
    try {
      files = fs.readdirSync(path.join(r, d.name))
    } catch {
      continue
    }
    for (const f of files) if (f.endsWith('.jsonl')) out.push(path.join(r, d.name, f))
  }
  return out
}

export function describe() {
  if (!detect()) return { present: false, root: ROOT() }
  const files = transcripts()
  return { present: true, root: ROOT(), transcripts: files.length }
}

// Content is a string, or an array of blocks where only `type: "text"` counts.
const textOf = (message) => {
  const c = message?.content
  if (typeof c === 'string') return c
  if (Array.isArray(c)) {
    return c
      .filter((b) => b && b.type === 'text' && typeof b.text === 'string')
      .map((b) => b.text)
      .join('\n')
  }
  return ''
}

const isHuman = (rec) =>
  rec.type === 'user' &&
  !rec.isSidechain &&
  !rec.isMeta &&
  !rec.toolUseResult &&
  !rec.sourceToolUseID

export function load({ since = 0 } = {}) {
  const out = []
  for (const file of transcripts()) {
    let lines
    try {
      lines = fs.readFileSync(file, 'utf8').split('\n')
    } catch {
      continue
    }

    const messages = []
    let sessionId = path.basename(file, '.jsonl')
    let cwd = null
    let title = null
    let branch = null

    for (const line of lines) {
      if (!line.trim()) continue
      let rec
      try {
        rec = JSON.parse(line)
      } catch {
        continue
      }
      if (rec.sessionId) sessionId = rec.sessionId
      if (rec.cwd && !cwd) cwd = rec.cwd
      if (rec.gitBranch && !branch) branch = rec.gitBranch
      if (rec.type === 'custom-title' && rec.customTitle) title = rec.customTitle
      else if (rec.type === 'ai-title' && rec.aiTitle && !title) title = rec.aiTitle

      if (!isHuman(rec)) continue
      const text = textOf(rec.message).trim()
      if (text.length < 2) continue
      const at = rec.timestamp ? Date.parse(rec.timestamp) : 0
      messages.push({ at: Number.isFinite(at) ? at : 0, text })
    }

    if (!messages.length) continue
    messages.sort((a, b) => a.at - b.at)
    const latest = messages[messages.length - 1].at
    if (latest <= since) continue

    // Claude Code has no project-identity record equivalent to opencode's, so
    // `cwd` is the best available repo key. Worktrees of one repo therefore
    // count separately here; the concentration stat is correspondingly softer.
    const dir = cwd ?? '(unknown)'
    out.push({
      id: sessionId,
      harness: name,
      project: dir,
      repo: dir,
      title: title ?? '(untitled)',
      createdAt: messages[0].at || latest,
      messages,
    })
  }
  return out
}
